"""stage-amdgpu — stage amdgpu DKMS source from a GitHub release tarball.

Ports scripts/stage-amdgpu-from-tarball.  Avoids all git operations so it
works cleanly inside CI containers.  Tags and branch heads are both supported;
tags are tried first.

Output layout matches what build-amdgpu-dkms and fast-build-amdgpu expect
(the same layout produced by 'git archive' from the amdgpu tree):
  amd/          — AMD GPU driver + DKMS build system
  ttm/          — TTM memory manager
  scheduler/    — GPU scheduler
  include/      — kcl, drm, uapi headers
  drm_*.c       — out-of-tree DRM core files
  Makefile      — symlink → amd/dkms/Makefile
  dkms.conf     — symlink → amd/dkms/dkms.conf
  configure     — generated by autoconf (required by pre-build.sh)
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request
from pathlib import Path

from ktool._util import die, require_cmds

_REPO = "ROCm/amdgpu"


def register(sub: argparse._SubParsersAction) -> None:
    p = sub.add_parser("stage-amdgpu",
                        help="Stage amdgpu DKMS source from a GitHub release tarball")
    p.add_argument("ref",
                   help="amdgpu ref to fetch (e.g. rocm-6.2.4, therock-7.14)")
    p.add_argument("output_dir",
                   help="Output directory for the staged DKMS source tree")
    p.add_argument("--repo", default=_REPO,
                   help=f"GitHub repo (default: {_REPO})")
    p.set_defaults(func=run_cmd)


def _fetch_tarball(ref: str, repo: str, work_dir: Path) -> Path:
    tarball = work_dir / "amdgpu.tar.gz"
    for url_tmpl in [
        f"https://github.com/{repo}/archive/refs/tags/{ref}.tar.gz",
        f"https://github.com/{repo}/archive/refs/heads/{ref}.tar.gz",
    ]:
        try:
            print(f"  Fetching {url_tmpl}...")
            urllib.request.urlretrieve(url_tmpl, tarball)
            print(f"  Downloaded from {url_tmpl}")
            return tarball
        except Exception:
            continue
    die(f"Could not fetch tarball for ref '{ref}' from {repo}.")


def _cp_tree(src_root: Path, rel: str, dst: Path, strip: int) -> None:
    full = src_root / rel
    if not full.exists():
        print(f"  (skipping missing: {rel})")
        return
    with tarfile.open(fileobj=subprocess.Popen(
            ["tar", "-c", "-C", str(src_root), rel],
            stdout=subprocess.PIPE).stdout) as tf:
        for m in tf.getmembers():
            parts = Path(m.name).parts
            if len(parts) <= strip:
                continue
            m.name = str(Path(*parts[strip:]))
            tf.extract(m, path=str(dst))


def _extract_tree(src_root: Path, rel: str, dst: Path, strip: int) -> None:
    """Extract a subdirectory tree using Python's tarfile."""
    full = src_root / rel
    if not full.exists():
        print(f"  (skipping missing: {rel})")
        return
    # Use subprocess tar for robustness with symlinks and permissions
    subprocess.run(
        ["tar", "-c", "-C", str(src_root), rel],
        stdout=subprocess.PIPE,
        check=True,
    )
    cmd_tar = subprocess.Popen(
        ["tar", "-c", "-C", str(src_root), rel],
        stdout=subprocess.PIPE,
    )
    dst.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["tar", "-x", f"--strip-components={strip}", "-C", str(dst)],
        stdin=cmd_tar.stdout,
        check=True,
    )
    cmd_tar.wait()


def _extract_file(src_root: Path, rel: str, dst: Path, strip: int) -> None:
    src = src_root / rel
    if not src.exists():
        print(f"  (skipping missing: {rel})")
        return
    dst.mkdir(parents=True, exist_ok=True)
    cmd_tar = subprocess.Popen(
        ["tar", "-c", "-C", str(src_root), rel],
        stdout=subprocess.PIPE,
    )
    subprocess.run(
        ["tar", "-x", f"--strip-components={strip}", "-C", str(dst)],
        stdin=cmd_tar.stdout,
        check=True,
    )
    cmd_tar.wait()


def run_cmd(args: argparse.Namespace) -> int:
    require_cmds("curl", "tar", "autoconf", "automake", "aclocal", "autoheader")

    output = Path(args.output_dir)

    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)

        # Download
        tarball = work / "amdgpu.tar.gz"
        repo = args.repo
        ref = args.ref
        fetched = False
        for url in [
            f"https://github.com/{repo}/archive/refs/tags/{ref}.tar.gz",
            f"https://github.com/{repo}/archive/refs/heads/{ref}.tar.gz",
        ]:
            try:
                print(f"Fetching {url}...")
                urllib.request.urlretrieve(url, str(tarball))
                fetched = True
                break
            except Exception:
                continue
        if not fetched:
            die(f"Could not fetch tarball for ref '{ref}' from {repo}")

        # Extract (strip the top-level <repo>-<ref>/ directory)
        src = work / "src"
        src.mkdir()
        subprocess.run(
            ["tar", "-xzf", str(tarball), "--strip-components=1", "-C", str(src)],
            check=True,
        )

        # Build output tree
        if output.exists():
            shutil.rmtree(output)
        for d in [
            output,
            output / "include/kcl",
            output / "include/drm",
            output / "include/uapi/drm",
            output / "include/uapi/linux",
            output / "amd/amdkcl/dma-buf",
            output / "include/linux",
        ]:
            d.mkdir(parents=True, exist_ok=True)

        print("Staging DKMS source layout...")

        # Main subtrees (strip drivers/gpu/drm/ = 3 components)
        _extract_tree(src, "drivers/gpu/drm/amd",       output,              3)
        _extract_tree(src, "drivers/gpu/drm/ttm",       output,              3)
        _extract_tree(src, "drivers/gpu/drm/scheduler", output,              3)

        # Out-of-tree DRM core files
        for f in ("drm_gem_ttm_helper.c", "drm_buddy.c", "drm_exec.c",
                  "drm_suballoc.c"):
            _extract_file(src, f"drivers/gpu/drm/{f}", output, 3)

        # backport/ — version macros (DRM_VER, DRM_PATCH, DRM_SUB) and compat
        # shims included via backport/backport.h; required by fast-build path
        _extract_tree(src, "backport", output / "backport", 0)

        # kcl headers
        _extract_tree(src, "include/kcl", output / "include", 1)

        # drm headers
        _extract_tree(src, "include/drm/ttm", output / "include/drm", 2)
        for f in ("amd_asic_type.h", "amd_rdma.h", "spsc_queue.h",
                  "drm_buddy.h", "drm_exec.h", "drm_gem_ttm_helper.h",
                  "gpu_scheduler.h"):
            _extract_file(src, f"include/drm/{f}", output / "include/drm", 2)

        # uapi headers
        _extract_file(src, "include/uapi/drm/amdgpu_drm.h",
                      output / "include/uapi/drm", 3)
        for f in ("kfd_ioctl.h", "kfd_sysfs.h"):
            _extract_file(src, f"include/uapi/linux/{f}",
                          output / "include/uapi/linux", 3)

        # dma-resv
        _extract_file(src, "drivers/dma-buf/dma-resv.c",
                      output / "amd/amdkcl/dma-buf", 2)
        _extract_file(src, "include/linux/dma-resv.h",
                      output / "include/linux", 2)

        # rename_symbol.h — injected via compiler -include flag by the amdgpu Kbuild
        _extract_file(src, "include/rename_symbol.h", output / "include", 1)

    # Symlinks
    makefile_link = output / "Makefile"
    dkms_link = output / "dkms.conf"
    if not makefile_link.exists():
        makefile_link.symlink_to("amd/dkms/Makefile")
    if not dkms_link.exists():
        dkms_link.symlink_to("amd/dkms/dkms.conf")

    # Generate configure
    dkms_dir = output / "amd/dkms"
    if dkms_dir.exists():
        print("Generating configure script...")
        subprocess.run(["aclocal", "-I", "m4"], cwd=str(dkms_dir), check=True)
        subprocess.run(["autoheader"], cwd=str(dkms_dir), check=True)
        subprocess.run(["autoconf", "-o", "configure", "configure.ac"],
                       cwd=str(dkms_dir), check=True)

    print(f"Staging complete: {output}")
    return 0
